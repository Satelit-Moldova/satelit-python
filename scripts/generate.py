"""Generates src/satelit/types.py and src/satelit/_resources.py from spec/openapi.json and spec/methods.json.

Run ``python scripts/generate.py`` after updating the spec
(``curl -o spec/openapi.json https://api.satelit.md/openapi.json``).
"""

from __future__ import annotations

import json
import keyword
import re
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
SPEC = json.loads((ROOT / "spec/openapi.json").read_text(encoding="utf-8"))
MAP = json.loads((ROOT / "spec/methods.json").read_text(encoding="utf-8"))
SPEC["components"]["schemas"].update(json.loads((ROOT / "spec/overrides.json").read_text(encoding="utf-8"))["schemas"])
SCHEMAS = SPEC["components"]["schemas"]
HEADER = "# Generated by scripts/generate.py from spec/openapi.json. Do not edit by hand.\n"


def pascal(s: str) -> str:
    return re.sub(r"(?:^|[._\-\s])(\w)", lambda m: m.group(1).upper(), s)


def snake(s: str) -> str:
    return re.sub(r"(?<!^)([A-Z])", r"_\1", s).lower()


def ref_name(ref: str) -> str:
    return ref.rsplit("/", 1)[-1]


def pyname(name: str) -> str:
    """A query parameter as a Python keyword argument (``from`` -> ``from_``)."""
    return name + "_" if keyword.iskeyword(name) or name in ("lang", "timeout") else name


class TypeGen:
    """JSON Schema -> TypedDicts and type aliases."""

    def __init__(self) -> None:
        self.blocks: dict[str, str] = {}  # name -> code
        self.deps: dict[str, set[str]] = {}  # name -> names it must follow (bases)
        self.quote = False  # references stay bare: annotations are postponed, aliases come last
        self.aliases: set[str] = set()

    def expr(self, s: dict, hint: str) -> str:
        """A type expression; inline objects become named TypedDicts."""
        if not isinstance(s, dict) or not s:
            return "Any"
        if "$ref" in s:
            return self.ref(ref_name(s["$ref"]))
        if "allOf" in s:
            self.define(hint, s)
            return self.ref(hint)
        alts = s.get("oneOf") or s.get("anyOf")
        if alts:
            return self.union([self.expr(a, f"{hint}{i}" if i else hint) for i, a in enumerate(alts)])
        types = s["type"] if isinstance(s.get("type"), list) else ([s["type"]] if "type" in s else [])
        if "enum" in s:
            lits = ", ".join(json.dumps(v) for v in s["enum"] if v is not None)
            parts = [f"Literal[{lits}]"]
            if "null" in types or None in s["enum"]:
                parts.append("None")
            return self.union(parts)
        if not types:
            return self.obj(s, hint) if "properties" in s else "Any"
        return self.union([self.one(t, s, hint) for t in types])

    @staticmethod
    def union(parts: list[str]) -> str:
        uniq = list(dict.fromkeys(parts))
        if len(uniq) == 1:
            return uniq[0]
        if "None" in uniq:
            rest = [p for p in uniq if p != "None"]
            inner = rest[0] if len(rest) == 1 else f"Union[{', '.join(rest)}]"
            return f"Optional[{inner}]"
        return f"Union[{', '.join(uniq)}]"

    def one(self, t: str, s: dict, hint: str) -> str:
        if t == "string":
            return "str"
        if t == "integer":
            return "int"
        if t == "number":
            return "float"
        if t == "boolean":
            return "bool"
        if t == "null":
            return "None"
        if t == "array":
            return f"List[{self.expr(s.get('items', {}), hint + 'Item')}]"
        if t == "object":
            return self.obj(s, hint)
        return "Any"

    def obj(self, s: dict, hint: str) -> str:
        if not s.get("properties"):
            extra = s.get("additionalProperties")
            if isinstance(extra, dict) and extra:
                return f"Dict[str, {self.expr(extra, hint + 'Value')}]"
            return "Dict[str, Any]"
        self.define(hint, s)
        return self.ref(hint)

    def ref(self, name: str) -> str:
        return f'"{name}"' if self.quote else name

    def define(self, name: str, s: dict) -> None:
        if name in self.blocks:
            return
        self.blocks[name] = ""  # reserve (recursion)
        bases: list[str] = []
        props: dict = {}
        required: set[str] = set()
        parts = s.get("allOf") or [s]
        for part in parts:
            if "$ref" in part:
                bases.append(ref_name(part["$ref"]))
            else:
                props.update(part.get("properties", {}))
                required |= set(part.get("required", []))
        self.deps[name] = set(bases)
        fields = {k: self.expr(v, name + pascal(k)) for k, v in props.items()}
        doc = (s.get("description") or "").split("\n")[0].strip()
        self.blocks[name] = self.typeddict(name, fields, required, bases, doc)

    @staticmethod
    def typeddict(name: str, fields: dict, required: set, bases: list, doc: str) -> str:
        valid = all(k.isidentifier() and not keyword.iskeyword(k) for k in fields)
        if not valid:
            # The functional form is evaluated at import: quote the names it refers to.
            body = ", ".join(f"{json.dumps(k)}: {quote_names(v)}" for k, v in fields.items())
            return f"{name} = TypedDict({json.dumps(name)}, {{{body}}}, total=False)\n"
        req = {k: v for k, v in fields.items() if k in required}
        opt = {k: v for k, v in fields.items() if k not in required}
        out = []
        base = ", ".join(bases) or "TypedDict"
        docline = f'    """{doc.replace(chr(34) * 3, "")}"""\n' if doc else ""
        if req and opt:
            out.append(f"class _{name}Required({base}):\n" + "".join(f"    {k}: {v}\n" for k, v in req.items()))
            out.append(
                f"class {name}(_{name}Required, total=False):\n{docline}"
                + "".join(f"    {k}: {v}\n" for k, v in opt.items())
            )
        elif opt:
            out.append(
                f"class {name}({base}, total=False):\n{docline}" + "".join(f"    {k}: {v}\n" for k, v in opt.items())
            )
        else:
            lines = "".join(f"    {k}: {v}\n" for k, v in req.items()) or ("" if docline else "    pass\n")
            out.append(f"class {name}({base}):\n{docline}{lines}")
        return "\n\n".join(out)

    def alias(self, name: str, s: dict) -> None:
        self.blocks[name] = f"{name} = {self.expr(s, name + 'Item')}\n"
        self.deps[name] = set()

    def ordered(self) -> list[str]:
        """Classes first (each after its bases), then aliases (each after the aliases it names)."""
        done: list[str] = []
        seen: set[str] = set()

        def deps(n: str) -> set[str]:
            if n in self.aliases:
                words = set(re.findall(r"[A-Za-z_]\w*", self.blocks[n].split("=", 1)[1]))
                return {w for w in words if w in self.aliases and w != n}
            return self.deps.get(n, set())

        def visit(n: str) -> None:
            if n in seen:
                return
            seen.add(n)
            for d in sorted(deps(n)):
                visit(d)
            done.append(n)

        for n in self.blocks:
            if n not in self.aliases:
                visit(n)
        for n in self.blocks:
            visit(n)
        return [self.blocks[n] for n in done]


TYPING_NAMES = {"Any", "Dict", "List", "Literal", "Optional", "Union", "None"}


def quote_names(expr: str) -> str:
    """Quotes the schema names in a type expression, leaving string literals alone."""
    parts = re.split(r'("(?:[^"\\]|\\.)*")', expr)
    for i in range(0, len(parts), 2):
        parts[i] = re.sub(
            r"\b([A-Z]\w*)\b", lambda m: m.group(1) if m.group(1) in TYPING_NAMES else f'"{m.group(1)}"', parts[i]
        )
    return "".join(parts)


def credits(op: dict) -> str:
    if op.get("security") == []:
        return "No key, 0 credits"
    desc = op.get("description") or ""
    m = re.search(r"(?:^|\s)costs? ([^.]*)\.", desc, re.I)
    c = f"Costs {m.group(1)}" if m else ""
    plan = re.match(r"^(Business and Enterprise|Enterprise)\.", desc)
    if plan:
        c = f"{plan.group(1)} plans only. {c}"
    return c


def main() -> None:
    tg = TypeGen()
    for name, s in SCHEMAS.items():
        if s.get("type") == "object" or "properties" in s or "allOf" in s:
            tg.define(name, s)
        else:
            tg.alias(name, s)

    namespaces: dict[str, list[dict]] = {}
    top: list[dict] = []
    for path, full in MAP["methods"]:
        op = SPEC["paths"][path]["get"]
        *ns_parts, method = full.split(".")
        ns = ".".join(ns_parts)
        hint = pascal(f"{ns}.{method}" if ns else method)
        params = [p for p in op.get("parameters", []) if p["name"] != "lang"]
        sch = op["responses"]["200"]["content"].get("application/json", {}).get("schema", {})
        data = sch.get("properties", {}).get("data")
        dtype = tg.expr(data, hint + "Data") if data else "Any"
        m = {
            "path": path,
            "name": snake(method),
            "op": op,
            "path_params": [p for p in params if p["in"] == "path"],
            "query": [p for p in params if p["in"] == "query"],
            "data": dtype,
        }
        (namespaces.setdefault(ns, []) if ns else top).append(m)

    # ---- types.py
    types_py = [
        HEADER,
        '"""Typed shapes of the API\'s answers (``data``), from the OpenAPI document."""\n',
        "from __future__ import annotations\n",
        "from typing import Any, Dict, List, Literal, Optional, TypedDict, Union\n\n",
    ]
    types_py.append("\n\n".join(tg.ordered()))
    (ROOT / "src/satelit/types.py").write_text("\n".join(types_py).rstrip() + "\n", encoding="utf-8", newline="\n")

    # ---- _resources.py
    def py_type(p: dict) -> str:
        s = p.get("schema", {})
        t = tg.expr(s, "Param")
        if s.get("type") == "boolean":
            t = "bool"
        if p["name"] in ("types", "seen", "exclude_flags") and t == "str":
            t = "Union[str, Sequence[str]]"
        return t

    def method_code(m: dict, is_async: bool, recv: str) -> str:
        args = ["self"]
        for p in m["path_params"]:
            args.append(f"{p['name']}: {'Union[int, str]' if p.get('schema', {}).get('type') == 'integer' else 'str'}")
        args.append("*")
        q = []
        for p in sorted(m["query"], key=lambda p: not p.get("required")):
            n = pyname(p["name"])
            t = py_type(p)
            args.append(
                f"{n}: {t}"
                if p.get("required")
                else f"{n}: Optional[{t}] = None"
                if not t.startswith("Optional[")
                else f"{n}: {t} = None"
            )
            q.append(f'"{p["name"]}": {n}')
        args += ["lang: Optional[Lang] = None", "timeout: Optional[float] = None"]
        path = m["path"]
        path_expr = ('f"' + re.sub(r"\{(\w+)\}", r"{_seg(\1)}", path) + '"') if m["path_params"] else f'"{path}"'
        query = "{" + ", ".join(q) + "}" if q else "None"
        doc = f"{m['op']['summary']}." + (f" {credits(m['op'])}." if credits(m["op"]) else "") + f" ``GET {path}``"
        sig = ",\n        ".join(args)
        kw = "async def" if is_async else "def"
        call = f"await {recv}._aget" if is_async else f"{recv}._get"
        return (
            f"    {kw} {m['name']}(\n        {sig},\n    ) -> Response[{m['data']}]:\n"
            f'        """{doc}"""\n'
            f"        return {call}({path_expr}, {query}, lang=lang, timeout=timeout)\n"
        )

    helpers = {"feed": ("_FeedHelpers", "_AsyncFeedHelpers")}
    res = [
        HEADER
        + '"""The typed namespaces of :class:`satelit.Satelit` and :class:`satelit.AsyncSatelit`."""\n\n'
        + "from __future__ import annotations\n\n"
        + "from typing import TYPE_CHECKING, Any, Dict, List, Literal, Optional, Sequence, Union\n\n"
        + "from ._core import Lang, Response, _seg\n"
        + "from ._helpers import _AsyncFeedHelpers, _FeedHelpers\n\n"
        + "if TYPE_CHECKING:\n"
        + "    from ._client import AsyncSatelit, Satelit\n"
        + "    from .types import *\n\n"
        + "__all__: List[str] = []\n",
    ]
    ns_names = list(namespaces)
    for is_async in (False, True):
        prefix = "Async" if is_async else ""
        client_t = "AsyncSatelit" if is_async else "Satelit"
        for ns in ns_names:
            cls = f"{prefix}{pascal(ns)}Api"
            children = [n for n in ns_names if n.startswith(ns + ".") and n.count(".") == ns.count(".") + 1]
            base = f"({helpers[ns][1 if is_async else 0]})" if ns in helpers else ""
            lines = [f"class {cls}{base}:", f'    """{MAP["namespaces"].get(ns, ns)}."""\n']
            lines.append(f"    def __init__(self, client: {client_t}) -> None:")
            lines.append("        self._c = client")
            for c in children:
                lines.append(f"        self.{c.split('.')[-1]} = {prefix}{pascal(c)}Api(client)")
            lines.append("")
            for m in namespaces[ns]:
                lines.append(method_code(m, is_async, "self._c"))
            res.append("\n".join(lines) + "\n")
        # The top-level methods as a mixin.
        lines = [f"class _{prefix}TopLevel:", '    """me(), products(), plans(), status(), stats(), sample()."""\n']
        lines.append("    _aget: Any  # set by AsyncSatelit\n" if is_async else "    _get: Any  # set by BaseClient\n")
        for m in top:
            lines.append(method_code(m, is_async, "self"))
        res.append("\n".join(lines) + "\n")
        roots = [n for n in ns_names if "." not in n]
        lines = [
            f"def _{prefix.lower() + '_' if prefix else ''}attach(client: {client_t}) -> None:",
            '    """Sets the namespaces on a client."""',
        ]
        for n in roots:
            lines.append(f"    client.{n} = {prefix}{pascal(n)}Api(client)  # type: ignore[attr-defined]")
        res.append("\n".join(lines) + "\n")
        # Declarations for type checkers.
        lines = [f"class _{prefix}Namespaces:", '    """Attribute types of the namespaces."""\n']
        for n in roots:
            lines.append(f"    {n}: {prefix}{pascal(n)}Api")
        res.append("\n".join(lines) + "\n")

    out = "\n\n".join(res).rstrip() + "\n"
    (ROOT / "src/satelit/_resources.py").write_text(out, encoding="utf-8", newline="\n")

    table = []
    for ns in ns_names:
        for m in namespaces[ns]:
            table.append([f"{ns}.{m['name']}", m["path"], credits(m["op"]), sig_short(m)])
    for m in top:
        table.append([m["name"], m["path"], credits(m["op"]), sig_short(m)])
    (ROOT / "spec/method-table.json").write_text(
        json.dumps(table, indent=1, ensure_ascii=False) + "\n", encoding="utf-8", newline="\n"
    )

    readme = ROOT / "README.md"
    if readme.exists():
        rows = [f"| `{n}({a})` | `{p}` | {c.replace('|', '/')} |" for n, p, c, a in table]
        block = "\n".join(
            ["<!-- methods:start -->", "| Method | Route | Credits |", "|---|---|---|", *rows, "<!-- methods:end -->"]
        )
        text = readme.read_text(encoding="utf-8")
        text = re.sub(r"<!-- methods:start -->.*<!-- methods:end -->", lambda _: block, text, flags=re.S)
        readme.write_text(text, encoding="utf-8", newline="\n")
    print(f"types: {len(SCHEMAS)}, methods: {len(table)}")


def sig_short(m: dict) -> str:
    a = [p["name"] for p in m["path_params"]]
    req = [pyname(p["name"]) + "=…" for p in m["query"] if p.get("required")]
    a += req
    if any(not p.get("required") for p in m["query"]):
        a.append("…")
    return ", ".join(a)


if __name__ == "__main__":
    main()
